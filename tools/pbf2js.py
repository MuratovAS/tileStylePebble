"""
Converts Pebble system fonts (.pbf from the firmware) into config/js/sysfonts.js
so the preview draws text with the same pixels as the watch.

    python3 tools/pbf2js.py <path to PebbleOS/resources> > config/js/sysfonts.js

Fonts are taken from the PebbleOS repository (resources/*/base/pbf). Only
Basic Latin and Latin-1 are kept (firmware fonts have no Cyrillic), plus the
wildcard glyph the watch draws for missing glyphs.

Glyph: [width, height, left offset, top offset, advance, base64 bits].
Bits go row by row, high bit of a byte first. The top offset is measured from
the top of the line, as in the firmware.
"""
import base64
import glob
import json
import os
import sys

import pbf

FONTS = [
    'GOTHIC_14', 'GOTHIC_14_BOLD',
    'GOTHIC_18', 'GOTHIC_18_BOLD',
    'GOTHIC_24', 'GOTHIC_24_BOLD',
    'GOTHIC_28', 'GOTHIC_28_BOLD',
    'BITHAM_30_BLACK',
    'BITHAM_42_BOLD',
]

CHARSET = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100))


def pack(bits):
    out = bytearray((len(bits) + 7) // 8)
    for i, b in enumerate(bits):
        if b:
            out[i >> 3] |= 0x80 >> (i & 7)
    return base64.b64encode(bytes(out)).decode('ascii')


def main(resources):
    result = {}
    for name in FONTS:
        found = glob.glob(os.path.join(resources, '*', 'base', 'pbf', name + '.pbf'))
        if not found:
            sys.exit('font not found: ' + name)
        font = pbf.load(found[0])
        keep = (CHARSET | {font['wildcard']}) & set(font['glyphs'])
        glyphs = {}
        for cp in sorted(keep):
            g = font['glyphs'][cp]
            glyphs[chr(cp)] = [g['w'], g['h'], g['left'], g['top'], g['adv'], pack(g['bits'])]
        result[name] = {
            'height': font['max_height'],
            'wildcard': chr(font['wildcard']) if font['wildcard'] in keep else '',
            'glyphs': glyphs,
        }
    print('/* Generated by tools/pbf2js.py from PebbleOS firmware fonts. Do not edit by hand. */')
    print('this.PebbleSysFonts = ' + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ';')


if __name__ == '__main__':
    main(sys.argv[1])
