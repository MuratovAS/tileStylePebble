"""
Text fonts the theme can pick instead of the firmware's Gothic: renders each
family from TTF at the text sizes 14, 18, 24 and 28 (regular and bold).

    ~/.local/share/uv/tools/pebble-tool/bin/python tools/textfonts.py <ttf cache dir>

Needs the Python of pebble-tool (it has freetype). Faces are rendered by the
SDK's own fontgen.py with the settings of a "font" resource, and both sides
are built from the result, so the preview shows the pixels of the watch:

- resources/fonts/text/*.pbf          the fonts, "font" resources of the app
- package.json                        their media entries (TEXT_*)
- src/c/gen_textfonts.h               resource id table, [family][SysFont]
- config/js/textfonts/<key>.js        the same glyphs for the preview
- config/js/textfonts/index.js        family keys and names, in protocol order

Missing TTFs are downloaded into the cache dir. The protocol stores a family
as its position here (0 is Gothic), so new families go to the end and
src/pkjs/protocol.js (TEXT_FONTS) is updated with them.
"""
import glob
import json
import os
import sys
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pbf  # noqa: E402
from pbf2js import font_json  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PBF_DIR = os.path.join(ROOT, 'resources', 'fonts', 'text')
JS_DIR = os.path.join(ROOT, 'config', 'js', 'textfonts')
SDK_TOOLS = os.path.expanduser('~/.local/share/pebble-sdk/SDKs/current/sdk-core/pebble/common/tools')

# in the order of SysFont (src/c/fonts.h): size, then regular before bold
SIZES = [14, 18, 24, 28]
# Basic Latin and Latin-1, as the firmware fonts in config/js/sysfonts.js
CHARACTER_REGEX = '[ -~ -ÿ]'
# pebble_sdk_platform.py, every platform
MAX_GLYPH_SIZE = 256

ROBOTO = 'https://raw.githubusercontent.com/googlefonts/roboto-2/main/src/hinted/'
GF = 'https://raw.githubusercontent.com/google/fonts/main/'

# key (letters and "_" only: the SDK takes a font's height from the first
# number in its resource name), name, regular TTF, bold TTF, license
FAMILIES = [
    ('roboto', 'Roboto', ROBOTO + 'Roboto-Regular.ttf', ROBOTO + 'Roboto-Bold.ttf', 'Apache-2.0'),
    ('roboto_condensed', 'Roboto Condensed', ROBOTO + 'RobotoCondensed-Regular.ttf',
     ROBOTO + 'RobotoCondensed-Bold.ttf', 'Apache-2.0'),
    ('fira', 'Fira Sans', GF + 'ofl/firasans/FiraSans-Regular.ttf', GF + 'ofl/firasans/FiraSans-Bold.ttf', 'OFL-1.1'),
    ('ubuntu', 'Ubuntu', GF + 'ufl/ubuntu/Ubuntu-Regular.ttf', GF + 'ufl/ubuntu/Ubuntu-Bold.ttf', 'UFL-1.0'),
    ('barlow', 'Barlow', GF + 'ofl/barlow/Barlow-Regular.ttf', GF + 'ofl/barlow/Barlow-Bold.ttf', 'OFL-1.1'),
    ('barlow_condensed', 'Barlow Condensed', GF + 'ofl/barlowcondensed/BarlowCondensed-Regular.ttf',
     GF + 'ofl/barlowcondensed/BarlowCondensed-Bold.ttf', 'OFL-1.1'),
    ('lato', 'Lato', GF + 'ofl/lato/Lato-Regular.ttf', GF + 'ofl/lato/Lato-Bold.ttf', 'OFL-1.1'),
    ('pt_sans', 'PT Sans', GF + 'ofl/ptsans/PT_Sans-Web-Regular.ttf', GF + 'ofl/ptsans/PT_Sans-Web-Bold.ttf',
     'OFL-1.1'),
    ('plex_condensed', 'IBM Plex Sans Condensed', GF + 'ofl/ibmplexsanscondensed/IBMPlexSansCondensed-Regular.ttf',
     GF + 'ofl/ibmplexsanscondensed/IBMPlexSansCondensed-Bold.ttf', 'OFL-1.1'),
]


def fetch(url, cache):
    path = os.path.join(cache, os.path.basename(url))
    if not os.path.exists(path):
        sys.stderr.write('download ' + url + '\n')
        with urllib.request.urlopen(url) as r:
            data = r.read()
        with open(path, 'wb') as f:
            f.write(data)
    return path


def render(fontgen, ttf, size):
    font = fontgen.Font(ttf, size, fontgen.MAX_GLYPHS, MAX_GLYPH_SIZE, False)
    font.set_regex_filter(CHARACTER_REGEX)
    font.build_tables()
    return font.bitstring()


# (suffix of the face in file and resource names, size, bold), SysFont order
def faces():
    for size in SIZES:
        yield '%d' % size, size, False
        yield '%d_bold' % size, size, True


def write_package(names):
    pkg_path = os.path.join(ROOT, 'package.json')
    with open(pkg_path) as f:
        pkg = json.load(f)
    media = [r for r in pkg['pebble']['resources']['media'] if not r['name'].startswith('TEXT_')]
    # after the clock fonts, before the icons
    at = next((i for i, r in enumerate(media) if r['name'].startswith('ICON_')), len(media))
    media[at:at] = [{'type': 'font', 'name': 'TEXT_' + n.upper(), 'file': 'fonts/text/%s.pbf' % n} for n in names]
    pkg['pebble']['resources']['media'] = media
    with open(pkg_path, 'w') as f:
        json.dump(pkg, f, indent=2, ensure_ascii=False)
        f.write('\n')


def write_header():
    out = ['/* Generated by tools/textfonts.py. Do not edit by hand. */', '#pragma once', '',
           '// Theme text fonts after Gothic (protocol value 1..), one resource per SysFont',
           '#define TEXT_FAMILY_COUNT %d' % (len(FAMILIES) + 1), '', '#define TEXT_FONT_RESOURCE_TABLE { \\']
    for key, *_ in FAMILIES:
        out.append('  {%s}, \\' % ', '.join('RESOURCE_ID_TEXT_%s_%s' % (key.upper(), s.upper()) for s, _, _ in faces()))
    out.append('}')
    with open(os.path.join(ROOT, 'src', 'c', 'gen_textfonts.h'), 'w') as f:
        f.write('\n'.join(out) + '\n')


def main(cache):
    sys.path.insert(0, SDK_TOOLS)
    from font import fontgen
    os.makedirs(cache, exist_ok=True)
    os.makedirs(PBF_DIR, exist_ok=True)
    os.makedirs(JS_DIR, exist_ok=True)
    for old in glob.glob(os.path.join(PBF_DIR, '*.pbf')) + glob.glob(os.path.join(JS_DIR, '*.js')):
        os.remove(old)

    names = []
    for key, name, regular, bold, lic in FAMILIES:
        preview = {}
        for suffix, size, is_bold in faces():
            data = render(fontgen, fetch(bold if is_bold else regular, cache), size)
            names.append('%s_%s' % (key, suffix))
            with open(os.path.join(PBF_DIR, names[-1] + '.pbf'), 'wb') as f:
                f.write(data)
            preview['%d%s' % (size, 'b' if is_bold else '')] = font_json(pbf.parse(data))
        with open(os.path.join(JS_DIR, key + '.js'), 'w', encoding='utf-8') as f:
            f.write('/* Generated by tools/textfonts.py from %s (%s). Do not edit by hand. */\n' % (name, lic))
            f.write('(this.PebbleTextFonts = this.PebbleTextFonts || {})[%s] = %s;\n'
                    % (json.dumps(key), json.dumps(preview, ensure_ascii=False, separators=(',', ':'))))

    with open(os.path.join(JS_DIR, 'index.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/textfonts.py. Do not edit by hand. */\n')
        f.write('this.PebbleTextFamilies = ' + json.dumps([[k, n] for k, n, *_ in FAMILIES], ensure_ascii=False) + ';\n')
    write_package(names)
    write_header()
    print('%d families x %d faces' % (len(FAMILIES), len(names) // len(FAMILIES)), file=sys.stderr)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
