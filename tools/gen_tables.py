"""
Generates src/c/gen_tables.c: font metrics the watch needs to lay out text
and the clock exactly like the settings page preview.

    python3 tools/gen_tables.py

- Firmware fonts (config/js/sysfonts.js): per glyph ink top, ink height and
  advance for Basic Latin + Latin-1 and the wildcard glyph. The watch has no
  API for ink bounds; the preview's measure/ink/fit/covers use these numbers.
- Clock fonts (config/js/fonts.js): advance and outline ink box of the digits
  and ':'. Boxes are measured by tools/clockbox.html in headless Chromium with
  the same code as the preview's glyphBox(), so the C clock layout matches it.
"""
import html
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from icons import find_chrome  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'c', 'gen_tables.c')

# order must match SysFont in src/c/fonts.h
SYSFONTS = ['GOTHIC_14', 'GOTHIC_14_BOLD', 'GOTHIC_18', 'GOTHIC_18_BOLD', 'GOTHIC_24', 'GOTHIC_24_BOLD',
            'GOTHIC_28', 'GOTHIC_28_BOLD', 'BITHAM_30_BLACK', 'BITHAM_42_BOLD']
FIRST, LAST = 0x20, 0xFF
CLOCK_FONTS = ['avenir', 'bold', 'leco']
CLOCK_CHARS = '0123456789:'


def load_js(path, var):
    text = open(path, encoding='utf-8').read()
    m = re.search(r'this\.' + var + r'\s*=\s*(\{.*\});?\s*$', text, re.S)
    return json.loads(m.group(1))


def sysfont_tables():
    fonts = load_js(os.path.join(ROOT, 'config', 'js', 'sysfonts.js'), 'PebbleSysFonts')
    lines = ['// [font][codepoint - 0x%02X]: {ink top, ink height, advance}; height 255 = no glyph' % FIRST,
             'const GlyphMetric g_glyph_metrics[SYSFONT_COUNT][%d] = {' % (LAST - FIRST + 1)]
    wild = []
    for name in SYSFONTS:
        f = fonts[name]
        row = []
        for cp in range(FIRST, LAST + 1):
            g = f['glyphs'].get(chr(cp))
            row.append('{%d,%d,%d}' % (g[3], g[1], g[4]) if g else '{0,255,0}')
        lines.append('  // ' + name)
        lines.append('  {' + ','.join(row) + '},')
        w = f['glyphs'].get(f['wildcard'])
        wild.append('{%d,%d,%d}' % (w[3], w[1], w[4]) if w else '{0,0,0}')
    lines.append('};')
    lines.append('')
    lines.append('// wildcard glyph (U+25AF), drawn for characters a font lacks')
    lines.append('const GlyphMetric g_glyph_wildcard[SYSFONT_COUNT] = {' + ','.join(wild) + '};')
    return lines


def clock_tables():
    chrome = find_chrome()
    page = 'file://' + os.path.join(ROOT, 'tools', 'clockbox.html')
    out = subprocess.run([chrome, '--headless', '--disable-gpu', '--allow-file-access-from-files',
                          '--virtual-time-budget=2000', '--dump-dom', page],
                         capture_output=True, text=True, check=True).stdout
    m = re.search(r'<pre id="out">(.*?)</pre>', out, re.S)
    if not m or not m.group(1).strip():
        sys.exit('clockbox.html returned nothing')
    data = json.loads(html.unescape(m.group(1)))
    lines = ['// Clock fonts: advance in 1/16 font units, ink box in 1/4 font units (y up)',
             'const ClockFontInfo g_clock_fonts[3] = {']
    for key in CLOCK_FONTS:
        f = data[key]
        glyphs = []
        for ch in CLOCK_CHARS:
            g = f['glyphs'][ch]
            b = g['box']
            for v in (b['x0'], b['x1'], b['top'], b['bottom']):
                assert v * 4 == int(v * 4)
            assert g['adv'] * 16 == int(g['adv'] * 16)
            glyphs.append('{%d,%d,%d,%d,%d}' % (round(g['adv'] * 16), round(b['x0'] * 4), round(b['x1'] * 4),
                                               round(b['top'] * 4), round(b['bottom'] * 4)))
        lines.append('  // %s' % key)
        lines.append('  {%d, {%s}},' % (round(f['upem'] * 16), ','.join(glyphs)))
    lines.append('};')
    return lines


def main():
    lines = ['/* Generated by tools/gen_tables.py. Do not edit by hand. */',
             '#include "fonts.h"', '']
    lines += sysfont_tables()
    lines.append('')
    lines += clock_tables()
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote ' + os.path.relpath(OUT, ROOT), file=sys.stderr)


if __name__ == '__main__':
    main()
