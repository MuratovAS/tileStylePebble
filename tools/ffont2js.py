"""
Converts fctx fonts (.ffont) into SVG outlines for the settings page preview.

    python3 tools/ffont2js.py <.ffont folder> > config/js/fonts.js

.ffont format (pebble-fctx): a header of 4 fixed16 (units_per_em, ascent,
descent, cap_height) and two uint16 (index and glyph table lengths), followed
by Unicode ranges, the glyph table and outline commands. fixed16 is an int16
scaled by 16.
"""
import struct, json, sys
NP = {ord('M'):2, ord('Z'):0, ord('L'):2, ord('H'):1, ord('V'):1, ord('C'):6, ord('S'):4, ord('Q'):4, ord('T'):2}
def parse(path):
    b = open(path,'rb').read()
    upem, asc, desc, cap, nidx, ntab = struct.unpack_from('<hhhhHH', b, 0)
    off = 12
    ranges = [struct.unpack_from('<HH', b, off+4*i) for i in range(nidx)]
    off += 4*nidx
    glyphs = [struct.unpack_from('<HHh', b, off+6*i) for i in range(ntab)]
    off += 6*ntab
    pd = b[off:]
    out = {}
    k = 0
    for (beg, end) in ranges:
        for u in range(beg, end):
            po, pl, adv = glyphs[k]; k += 1
            p = po; parts = []
            while p < po + pl:
                code, = struct.unpack_from('<H', pd, p); p += 2
                n = NP[code]
                vals = struct.unpack_from('<%dh' % n, pd, p); p += 2*n
                parts.append(chr(code) + ' '.join('%g' % (v/16) for v in vals))
            out[chr(u)] = {'d': ' '.join(parts), 'adv': adv/16}
    return {'upem': upem/16, 'ascent': asc/16, 'descent': desc/16, 'cap': cap/16, 'glyphs': out}
fonts = {}
for key, f in [('avenir','AvenirNextRegular'),('bold','AvenirNextDemiBold'),('leco','LECO1976-Regular')]:
    fonts[key] = parse(sys.argv[1] + '/' + f + '.ffont')
    g = fonts[key]
    print(key, g['upem'], g['ascent'], g['descent'], g['cap'], ''.join(sorted(g['glyphs'])), file=sys.stderr)
print('/* Generated by tools/ffont2js.py from TimeStyle fonts. Do not edit by hand. */')
print('this.PebbleFonts = ' + json.dumps(fonts, ensure_ascii=False, separators=(',', ':')) + ';')
